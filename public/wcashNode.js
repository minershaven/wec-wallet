"use strict";

// Bundled Wcash node (Miners Haven all-in-one build).
//
// The packaged Windows wallet ships `resources/node/wcash-zebrad.exe`, a Wolf
// `zebrad` built with `wcash-consensus`. This module runs it in the background
// so the wallet can sync from the user's own node instead of a public server:
//
// - the only listener the wallet needs is the node's lightwalletd gRPC feed,
//   bound to 127.0.0.1:48234 (the endpoint compiled into this build);
// - the JSON-RPC server is not configured at all, so no admin or mining calls
//   are reachable, and the P2P listener is bound to loopback so Windows never
//   asks to open a firewall port (outbound peer connections still work);
// - node data lives under %LOCALAPPDATA%\Wcash Wallet\node-mainnet, apart from
//   the roaming wallet profile.
//
// If something is already serving 127.0.0.1:48234 (for example another copy of
// the node), it is used as is and no second node is started.

const fs = require("fs");
const net = require("net");
const path = require("path");
const { spawn } = require("child_process");

const LIGHTWALLETD_HOST = "127.0.0.1";
const LIGHTWALLETD_PORT = 48234;
const P2P_LISTEN = "127.0.0.1:48233";
const MAX_LOG_BYTES = 20 * 1024 * 1024;
const MAX_RESTARTS = 5;
const RESTART_DELAY_MS = 5000;

const status = {
  enabled: false,
  state: "idle", // idle | starting | syncing | synced | external | stopped | error
  height: null,
  percent: null,
  remaining: null,
  peers: null,
  error: null,
  updatedAt: null,
};

let child = null;
let stopping = false;
let restarts = 0;
let logStream = null;

const setStatus = (patch) => Object.assign(status, patch, { updatedAt: Date.now() });

function nodeExecutablePath(resourcesPath) {
  return path.join(resourcesPath, "node", "wcash-zebrad.exe");
}

function nodeDataDir() {
  const base = process.env.LOCALAPPDATA || path.join(require("os").homedir(), "AppData", "Local");
  return path.join(base, "Wcash Wallet", "node-mainnet");
}

// TOML literal strings ('...') take Windows paths without escaping.
const tomlPath = (p) => `'${p.replace(/'/g, "")}'`;

function writeConfig(dataDir) {
  const config = [
    "# Generated by Wcash Wallet (all-in-one). Rewritten on every start.",
    "[network]",
    'network = "WcashMainnet"',
    `listen_addr = "${P2P_LISTEN}"`,
    `cache_dir = ${tomlPath(path.join(dataDir, "peers"))}`,
    "",
    "[state]",
    `cache_dir = ${tomlPath(path.join(dataDir, "state"))}`,
    "",
    "[rpc]",
    "# No JSON-RPC listener: only the wallet's compact-block feed, on loopback.",
    `lightwalletd_listen_addr = "${LIGHTWALLETD_HOST}:${LIGHTWALLETD_PORT}"`,
    "enable_cookie_auth = false",
    "",
    "[tracing]",
    'filter = "info"',
    "use_color = false",
    "",
  ].join("\n");
  const file = path.join(dataDir, "zebrad.toml");
  fs.writeFileSync(file, config);
  return file;
}

function portInUse(host, port) {
  return new Promise((resolve) => {
    const socket = net.connect({ host, port });
    const done = (inUse) => {
      socket.destroy();
      resolve(inUse);
    };
    socket.setTimeout(1000, () => done(false));
    socket.once("connect", () => done(true));
    socket.once("error", () => done(false));
  });
}

// zebrad progress lines look like:
//   ... estimated progress to chain tip sync_percent=42.123 % current_height=Height(28000) remaining_sync_blocks=38000 ...
//   ... finished initial sync to chain tip, using gossiped blocks sync_percent=100.000 % current_height=Height(66954) ...
function parseLogLine(line) {
  const percent = line.match(/sync_percent=([0-9.]+)\s*%/);
  const height = line.match(/current_height=Height\((\d+)\)/);
  const remaining = line.match(/remaining_sync_blocks=(\d+)/);
  const peers = line.match(/(?:ready_peers|open_peers|num_ready_peers)=(\d+)/);
  const patch = {};
  if (percent) patch.percent = Math.min(100, Number(percent[1]));
  if (height) patch.height = Number(height[1]);
  if (remaining) patch.remaining = Number(remaining[1]);
  if (peers) patch.peers = Number(peers[1]);
  if (/finished initial sync to chain tip/.test(line)) {
    patch.state = "synced";
    patch.percent = 100;
  } else if (percent && status.state !== "synced") {
    patch.state = Number(percent[1]) >= 99.9 ? "synced" : "syncing";
  }
  if (Object.keys(patch).length) setStatus(patch);
}

function openLog(dataDir) {
  const file = path.join(dataDir, "zebrad.log");
  try {
    if (fs.existsSync(file) && fs.statSync(file).size > MAX_LOG_BYTES) {
      fs.renameSync(file, `${file}.old`);
    }
  } catch {
    // a log that cannot be rotated is not a reason to stop the node
  }
  return fs.createWriteStream(file, { flags: "a" });
}

function launch(exe, dataDir) {
  const config = writeConfig(dataDir);
  logStream = logStream || openLog(dataDir);
  setStatus({ state: "starting", error: null });

  child = spawn(exe, ["-c", config, "start"], {
    cwd: dataDir,
    windowsHide: true,
    stdio: ["ignore", "pipe", "pipe"],
  });

  let pending = "";
  const onData = (chunk) => {
    const text = chunk.toString();
    logStream.write(text);
    pending += text;
    const lines = pending.split(/\r?\n/);
    pending = lines.pop();
    for (const line of lines) parseLogLine(line);
  };
  child.stdout.on("data", onData);
  child.stderr.on("data", onData);

  child.once("error", (err) => {
    setStatus({ state: "error", error: `The Wcash node could not start: ${err.message}` });
  });

  child.once("exit", (code, signal) => {
    child = null;
    if (stopping) {
      setStatus({ state: "stopped" });
      return;
    }
    if (restarts < MAX_RESTARTS) {
      restarts += 1;
      setStatus({ state: "starting", error: `The Wcash node stopped (code ${code ?? signal}); restarting.` });
      setTimeout(() => {
        if (!stopping) launch(exe, dataDir);
      }, RESTART_DELAY_MS);
    } else {
      setStatus({
        state: "error",
        error: `The Wcash node keeps stopping (code ${code ?? signal}). See ${path.join(dataDir, "zebrad.log")}.`,
      });
    }
  });
}

/**
 * Start the bundled node if this build has one. Never throws: a node problem
 * is reported through status(), and the wallet still opens.
 */
async function startWcashNode({ resourcesPath, isPackaged, profileId }) {
  try {
    if (!isPackaged || process.platform !== "win32" || profileId !== "mainnet-v1") return;
    const exe = nodeExecutablePath(resourcesPath);
    if (!fs.existsSync(exe)) return;
    setStatus({ enabled: true });

    if (await portInUse(LIGHTWALLETD_HOST, LIGHTWALLETD_PORT)) {
      setStatus({ state: "external", percent: null });
      return;
    }

    const dataDir = nodeDataDir();
    fs.mkdirSync(dataDir, { recursive: true });
    stopping = false;
    launch(exe, dataDir);
  } catch (err) {
    setStatus({ state: "error", error: `The Wcash node could not start: ${err.message}` });
  }
}

/** Stop the node. Safe to call more than once and from a process 'exit' handler. */
function stopWcashNode() {
  stopping = true;
  if (child) {
    try {
      child.kill();
    } catch {
      // already gone
    }
  }
  if (logStream) {
    try {
      logStream.end();
    } catch {
      // ignore
    }
    logStream = null;
  }
}

const wcashNodeStatus = () => ({ ...status, dataDir: status.enabled ? nodeDataDir() : null });

module.exports = { startWcashNode, stopWcashNode, wcashNodeStatus, parseLogLine };
